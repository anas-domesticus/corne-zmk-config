#!/usr/bin/env python3
"""Generate keymap_drawer.config.yaml mapping US HID legends to the characters a
UK ('gb', ideally 'gb extd') host will actually type, so the rendered keymap is
truthful.

Regenerate with:  ./.venv/bin/python gen_uk_config.py
"""
import yaml

RAW = {
    # number row (shifted states) -- UK differs from US on 2 and 3
    "&kp EXCL": "!",
    "&kp AT": '"',          # Shift+2 -> " on UK
    "&kp HASH": "\u00a3",   # Shift+3 -> £ on UK
    "&kp DLLR": "$",
    "&kp PRCNT": "%",
    "&kp CARET": "^",
    "&kp AMPS": "&",
    "&kp ASTRK": "*",
    "&kp LPAR": "(",
    "&kp RPAR": ")",
    "&kp UNDER": "_",
    "&kp PLUS": "+",
    # quote / hash / slash keys -- UK positions
    "&kp SQT": "'",
    "&kp LS(SQT)": "@",     # Shift+' -> @ on UK
    "&kp BSLH": "#",        # the #/~ key on UK
    "&kp LS(BSLH)": "~",
    "&kp NUBS": "\\",       # ISO key left of Z
    "&kp LS(NUBS)": "|",
    # brackets / punctuation
    "&kp LBKT": "[",
    "&kp LBRC": "{",
    "&kp RBKT": "]",
    "&kp RBRC": "}",
    "&kp SEMI": ";",
    "&kp COLON": ":",
    "&kp COMMA": ",",
    "&kp LS(COMMA)": "<",
    "&kp DOT": ".",
    "&kp LS(DOT)": ">",
    "&kp FSLH": "/",
    "&kp LS(FSLH)": "?",
    "&kp MINUS": "-",
    "&kp EQUAL": "=",
    "&uk_grave": "`",
    # accent macros
    "&fr_agrave": "à",
    "&fr_acirc": "â",
    "&fr_eacute": "é",
    "&fr_egrave": "è",
    "&fr_ecirc": "ê",
    "&fr_edier": "ë",
    "&fr_ugrave": "ù",
    "&fr_ucirc": "û",
    "&fr_udier": "ü",
    "&fr_icirc": "î",
    "&fr_idier": "ï",
    "&fr_ocirc": "ô",
    "&fr_cced": "ç",
    "&es_ntilde": "ñ",
    "&kp TILDE": "\u00ac",   # Shift+` -> ¬ on UK
    "&kp RA(N4)": "\u20ac",  # AltGr+4 -> €
    # app launchers (hyper = Cmd+Ctrl+Shift, matches Karabiner)
    "&kp LS(LG(LC(T)))": "Ghostty",
    "&kp LS(LG(LC(S)))": "Spotify",
    "&kp LS(LG(LC(B)))": "Brave",
    "&kp LS(LG(LC(SEMI)))": "Slack",
    # screenshot (macOS Cmd+Shift+4, area capture)
    "&kp LS(LG(N4))": "⌘⇧4",
}

config = {
    "draw_config": {"footer_text": "Corne - AZERTY letters on a UK host"},
    "parse_config": {"raw_binding_map": RAW},
}

with open("keymap_drawer.config.yaml", "w", encoding="utf-8") as fh:
    fh.write("# Generated by gen_uk_config.py - US HID -> UK output legends\n")
    yaml.safe_dump(config, fh, allow_unicode=True, sort_keys=False, width=10**6)

print("wrote keymap_drawer.config.yaml with", len(RAW), "legend mappings")
